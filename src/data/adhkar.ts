const HUSN = (n: number): string => `https://sunnah.com/hisn/${n + 1}`;

/** التلاوة الصوتية الأصلية من موقع حصن المسلم — تُشغَّل عند الطلب فقط */
const AUDIO = (n: number): string => `https://www.hisnmuslim.com/audio/ar/${n}.mp3`;

/** مرجع «حصن المسلم» — مُتحقَّق منه بفتح الصفحة */
const hisn = (n: number): SourceRef => ({
  book: "حصن المسلم",
  hadith: String(n),
  numberingNote: "ترقيم sunnah.com لكتاب حصن المسلم",
  url: HUSN(n),
  numberVerification: "confirmed",
});

/**
 * مرجع مجموعة أصلية مُتحقَّق منه بفتح الصفحة على sunnah.com
 * (الترقيم هو ترقيم sunnah.com — دار السلام لأبي داود والترمذي)
 */
const confirmed = (
  book: string,
  hadith: string,
  url: string,
  grade?: string,
  gradeNote?: string
): SourceRef => ({
  book,
  hadith,
  numberingNote: "ترقيم sunnah.com",
  url,
  grade,
  numberVerification: "confirmed",
  gradeNote,
});

/**
 * مرجع مذكور في «حصن المسلم» ولم يُتحقَّق من رقمه في ترقيم المجموعة الأصلية.
 * يُعرض دائمًا بمُوسوم «لم يُتحقق من رقم المجموعة الأصلية».
 */
const cited = (book: string, asCited: string, grade?: string): SourceRef => ({
  book,
  numberingNote: `كما ورد في حصن المسلم: ${asCited}`,
  grade,
  numberVerification: "unconfirmed",
});

