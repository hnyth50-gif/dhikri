const pick = (time: "morning" | "evening"): Dhikr[] =>
  DHKAR.filter((d) => d.time === time || d.time === "both");

export const SECTIONS: Record<"morning" | "evening", AdhkarSection> = {
  morning: {
    id: "morning",
    title: "أذكار الصباح",
    subtitle: "تُقال بعد صلاة الفجر إلى طلوع الشمس، وبعدها نافعة إلى الزوال",
    items: pick("morning"),
  },
  evening: {
    id: "evening",
    title: "أذكار المساء",
    subtitle: "تُقال بعد صلاة العصر إلى غروب الشمس، وبعدها نافعة إلى النوم",
    items: pick("evening"),
  },
};

export function getAdhkar(section: "morning" | "evening"): Dhikr[] {
  return SECTIONS[section].items;
}

/** البحث في كل الأذكار، مع تطبيع الهمزات والتشكيل التقريبية */
export function searchAdhkar(query: string): Dhikr[] {
  const q = normalize(query);
  if (!q) return [];
  return DHKAR.filter((d) => normalize(`${d.title} ${d.text} ${d.eveningText ?? ""} ${d.virtue ?? ""}`).includes(q));
}

export function findDhikr(id: string): Dhikr | undefined {
  return DHKAR.find((d) => d.id === id);
}

/** يزيل التشكيل ويوحّد صور الهمزات والألف المقصورة لتسهيل البحث العربي */
export function normalize(s: string): string {
  return s
    .replace(/[\u064B-\u0652\u0670\u06D6-\u06ED\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[«»"'،؛.!؟]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** الأذكار التي تحتاج مراجعة — تُعرض في صفحة المراجعة وفي الواجهة */
export function reviewQueue(): Dhikr[] {
  return DHKAR.filter((d) => d.verification !== "verified-source");
}

/** كل المراجع التي لم يُتحقق من رقمها في ترقيم المجموعة الأصلية */
export function unconfirmedNumbers(): Array<{ dhikr: Dhikr; source: SourceRef }> {
  const out: Array<{ dhikr: Dhikr; source: SourceRef }> = [];
  for (const d of DHKAR) {
    for (const s of d.sources) {
      if (s.numberVerification !== "confirmed") out.push({ dhikr: d, source: s });
    }
  }
  return out;
}

/** كلما يُظهر متن النص بحسب القسم والصيغة */
export function textFor(dhikr: Dhikr, section: "morning" | "evening"): string {
  return section === "evening" && dhikr.eveningText ? dhikr.eveningText : dhikr.text;
}
