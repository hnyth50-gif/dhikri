/**
 * فحص سلامة بيانات الأذكار — `npm run test:data`
 *
 * لا يفحص هذا السكربت الواجهة، بل ملف البيانات وحده:
 *   src/data/adhkar.ts  ← مصدر الحقيقة الوحيد للمحتوى.
 *
 * ما يتحقق منه:
 *   1.  البنية: حقول إلزامية، أنواع صحيحة، معرّفات فريدة.
 *   2.  الأعداد: عدد التكرار > 0 وصياغته الأصلية موجودة.
 *   3.  المراجع: أي مرجع موسوم «مُتحقَّق» لابد أن يحمل رابطًا صالحًا،
 *       وأي رقم غير مُتحقَّق لا يُعرض على أنه مُتحقَّق.
 *   4.  الآيات: كل ذكر من نوع quran يحمل مرجعًا قرآنيًا كاملًا.
 *   5.  الأقسام: الصباح والمساء يشتملان على كل ذكر مخصص لهما تمامًا.
 *   6.  النصوص: لا اختصار ولا نقاط نهاية ولا مسافات زائدة.
 *   7.  الروابط: صيغة رابط التلاوة ثابتة ومشتقّة من رقم الذكر.
 *
 * اختياري: `node scripts/validate-data.mjs --network`
 *   يفتح كل رابط مرجعي فعليًا (يحتاج اتصالًا بالإنترنت) ويطمئن على بقائه 200.
 *
 * لا يُخفي أي فشل: أي مخالفة ⇒ الخروج برمز 1.
 */

import { buildSync } from "esbuild";
import { pathToFileURL } from "node:url";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const DATA = resolve(ROOT, "src/data/adhkar.ts");
const CHECK_NETWORK = process.argv.includes("--network");

const problems = [];
const notes = [];
const fail = (msg) => problems.push(msg);
const ok = (msg) => notes.push(msg);

/* ---------------------------------------------------------------- */
/* 1. تجميع الوحدة عبر esbuild (لا يُضاف أي تبعية جديدة)             */
/* ---------------------------------------------------------------- */

let mod;
try {
  const outDir = mkdtempSync(join(tmpdir(), "dhikri-data-"));
  const outFile = join(outDir, "adhkar.mjs");
  buildSync({
    entryPoints: [DATA],
    bundle: true,
    format: "esm",
    platform: "neutral",
    outfile: outFile,
    logLevel: "silent",
  });
  mod = await import(pathToFileURL(outFile).href);
  writeFileSync(join(outDir, "README.txt"), "Generated by validate-data.mjs\n");
  ok(`تم تحميل وحدة البيانات (${DATA.replace(ROOT, ".")})`);
} catch (err) {
  console.error("✗ تعذّر تحميل ملف البيانات:\n" + (err?.message ?? err));
  process.exit(1);
}

const { DHKAR, SECTIONS, getAdhkar, searchAdhkar, reviewQueue, unconfirmedNumbers, textFor, normalize } = mod;

const KINDS = new Set(["quran", "hadith", "adhkar"]);
const TIMES = new Set(["morning", "evening", "both"]);
const VERIFICATIONS = new Set(["verified-source", "needs-review"]);
const NUMBER_VERIFICATIONS = new Set(["confirmed", "unconfirmed"]);

/* ---------------------------------------------------------------- */
/* 2. الجملة العامة                                                   */
/* ---------------------------------------------------------------- */

if (!Array.isArray(DHKAR) || DHKAR.length === 0) {
  fail("DHKAR ليس مصفوفة غير فارغة");
}
if (!SECTIONS?.morning || !SECTIONS?.evening) {
  fail("SECTIONS يجب أن يحوي morning وevening");
}

const seenIds = new Map();
const seenHisn = new Map();

for (const d of DHKAR ?? []) {
  const label = d.id ? `«${d.id}»` : "(بدون id)";

  /* --- الهوية --- */
  if (typeof d.id !== "string" || !d.id.trim()) fail(`${label}: id مفقود`);
  else if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(d.id))
    fail(`${label}: id يجب أن يكون لاتينيًا صغيرًا بلا مسافات (kebab-case)`);
  else if (seenIds.has(d.id)) fail(`${label}: id مكرر — سبق ظهوره في «${seenIds.get(d.id)}»`);
  else seenIds.set(d.id, d.title);

  /* --- الحقول النصية --- */
  for (const field of ["title", "text", "verificationNote", "countLabel"]) {
    const v = d[field];
    if (typeof v !== "string" || !v.trim()) fail(`${label}: الحقل «${field}» فارغ`);
    else if (v !== v.trim()) fail(`${label}: الحقل «${field}» فيه مسافات بداية/نهاية`);
  }

  /* --- النص لا يُختصر --- */
  for (const field of ["text", "eveningText"]) {
    const v = d[field];
    if (typeof v === "string" && /\s(\.{3,}|…)$/.test(v))
      fail(`${label}: النص في «${field}» ينتهي بنقاط — من الممنوع اختصار النص`);
  }

  /* --- التصنيف --- */
  if (!KINDS.has(d.kind)) fail(`${label}: kind غير صالح «${d.kind}»`);
  if (!TIMES.has(d.time)) fail(`${label}: time غير صالح «${d.time}»`);
  if (!VERIFICATIONS.has(d.verification))
    fail(`${label}: verification غير صالح «${d.verification}»`);

  /* --- العدد --- */
  if (!Number.isInteger(d.count) || d.count < 1)
    fail(`${label}: count يجب أن يكون عددًا صحيحًا موجبًا، حاليًا ${JSON.stringify(d.count)}`);
  if (d.eveningCount !== undefined && (!Number.isInteger(d.eveningCount) || d.eveningCount < 1))
    fail(`${label}: eveningCount غير صالح`);
  if (d.eveningText !== undefined && typeof d.eveningText !== "string")
    fail(`${label}: eveningText يجب أن يكون نصًا`);

  /* --- رقم الذكر في حصن المسلم --- */
  if (!Number.isInteger(d.hisn) || d.hisn < 1 || d.hisn > 400)
    fail(`${label}: hisn خارج المدى المعقول (${JSON.stringify(d.hisn)})`);
  else if (seenHisn.has(d.hisn))
    fail(`${label}: hisn=${d.hisn} مكرر — سابقه «${seenHisn.get(d.hisn)}»`);
  else seenHisn.set(d.hisn, d.id);

  /* --- الروابط الصوتية --- */
  if (d.audio !== undefined) {
    if (typeof d.audio !== "string" || !d.audio.startsWith("https://"))
      fail(`${label}: audio يجب أن يكون رابطًا آمنًا https — حاليًا ${JSON.stringify(d.audio)}`);
    else if (!new RegExp(`^https://www\\.hisnmuslim\\.com/audio/ar/${d.hisn}\\.mp3$`).test(d.audio))
      fail(`${label}: audio لا يطابق رقم الذكر (hisn=${d.hisn}) — ${d.audio}`);
  }

  /* --- المراجع --- */
  if (!Array.isArray(d.sources) || d.sources.length === 0) {
    fail(`${label}: لا توجد أي مرجع على الإطلاق — المحتوى بلا سند`);
  } else {
    d.sources.forEach((s, i) => {
      const at = `${label} → المصدر[${i}]`;
      if (typeof s?.book !== "string" || !s.book.trim()) fail(`${at}: اسم الكتاب مفقود`);
      if (!NUMBER_VERIFICATIONS.has(s.numberVerification))
        fail(`${at}: numberVerification غير صالح «${s.numberVerification}»`);

      if (s.numberVerification === "confirmed") {
        if (typeof s.url !== "string" || !/^https:\/\//.test(s.url))
          fail(`${at}: مرجع مُتحقَّق منه بلا رابط https صالح — لا يجوز عرضه كمُتحقَّق`);
        else if (!/sunnah\.com\//.test(s.url))
          fail(`${at}: الرابط ليس من نطاق sunnah.com — ${s.url}`);
        if (s.grade !== undefined && !String(s.grade).trim())
          fail(`${at}: grade موجود فارغ`);
      } else {
        // مرجع غير مُتحقَّق: يجب أن يحمل توضيحًا يمنع الاعتماد عليه
        if (!s.numberingNote) fail(`${at}: مرجع غير مُتحقَّق بلا numberingNote يوضح ذلك`);
      }
    });

    /* لا يجوز إدراج رقم غير مُتحقَّق ثم عرضه بلا وسم */
    const unconfirmedWithNumber = d.sources.filter(
      (s) => s.numberVerification !== "confirmed" && typeof s.hadith === "string"
    );
    for (const s of unconfirmedWithNumber) {
      if (!s.numberingNote?.includes("حصن المسلم"))
        fail(`${label}: رقم غير مُتحقَّق بلا إشارة إلى مصدره «${s.book}»`);
    }
  }

  /* --- الآيات --- */
  if (d.kind === "quran") {
    if (!Array.isArray(d.quran) || d.quran.length === 0)
      fail(`${label}: ذكر قرآني بلا مرجع قرآني (quran[])`);
    else
      d.quran.forEach((q, i) => {
        if (!q.surah || typeof q.surah !== "string") fail(`${label}: quran[${i}].surah مفقود`);
        if (!Number.isInteger(q.surahNumber) || q.surahNumber < 1 || q.surahNumber > 114)
          fail(`${label}: quran[${i}].surahNumber خارج 1..114 (${q.surahNumber})`);
        if (!Number.isInteger(q.from) || q.from < 1) fail(`${label}: quran[${i}].from غير صالح`);
        if (!Number.isInteger(q.to) || q.to < q.from)
          fail(`${label}: quran[${i}].to يجب أن يكون >= from`);
      });
  }

  /* --- المراجعة والتوثيق --- */
  if (d.verification !== "verified-source" && !d.verificationNote?.trim())
    fail(`${label}: في طابور المراجعة ويجب أن يحمل مبررًا (verificationNote)`);
  if (d.verification === "verified-source" && typeof d.hisn !== "number")
    fail(`${label}: موسوم مُتحقَّق لكنه بلا رقم في حصن المسلم`);
}

ok(`${DHKAR?.length} ذكرًا، ${seenHisn.size} رقمًا فريدًا في حصن المسلم`);

/* ---------------------------------------------------------------- */
/* 3. الأقسام                                                        */
/* ---------------------------------------------------------------- */

for (const key of ["morning", "evening"]) {
  const items = getAdhkar(key);
  if (!Array.isArray(items) || items.length === 0) {
    fail(`قسم «${key}» فارغ`);
    continue;
  }

  const ids = new Set();
  for (const d of items) {
    if (ids.has(d.id)) fail(`قسم «${key}»: «${d.id}» مكرر داخل القسم`);
    ids.add(d.id);
    if (key === "morning" && d.time === "evening")
      fail(`قسم «${key}» يحوي ذكرًا مخصصًا للمساء: «${d.id}»`);
    if (key === "evening" && d.time === "morning")
      fail(`قسم «${key}» يحوي ذكرًا مخصصًا للصباح: «${d.id}»`);
  }

  const expected = DHKAR.filter((d) => d.time === key || d.time === "both");
  const missing = expected.filter((d) => !ids.has(d.id));
  const extra = items.filter((d) => !expected.some((e) => e.id === d.id));
  for (const m of missing) fail(`قسم «${key}»: ناقص عنه «${m.id}» مع أنه مخصص له`);
  for (const e of extra) fail(`قسم «${key}»: زائد فيه «${e.id}» ولا يخصّه`);
}
ok(
  `الأقسام: صباح ${getAdhkar("morning")?.length} / مساء ${getAdhkar("evening")?.length}`
);

/* ---------------------------------------------------------------- */
/* 4. الفهارس المساعدة                                               */
/* ---------------------------------------------------------------- */

const allIds = new Set(DHKAR.map((d) => d.id));
if (searchAdhkar("")?.length !== 0) fail('searchAdhkar("") يجب أن يعيد []');

// كلمة موجودة في صيغة المساء وحدها: يجب أن يعثر عليها البحث رغم أنها ليست في النص الأساسي
const eveningOnly = DHKAR.find((d) => d.eveningText && !d.text.includes("أَمْسَيْنَا"));
if (eveningOnly && searchAdhkar("أمسينا").length === 0)
  fail(`searchAdhkar("أمسينا") لم يجد «${eveningOnly.id}» رغم وجوده في صيغة المساء`);

const sample = DHKAR.find((d) => d.id === "bismillah-la-yadurru") ?? DHKAR[0];
const hits = searchAdhkar("بسم الله");
if (hits.length === 0) fail('searchAdhkar("بسم الله") لم يجد أي ذكر');
if (!hits.some((r) => r.id === sample.id))
  fail(`searchAdhkar("بسم الله") لم يجد «${sample.id}»`);
for (const r of hits) {
  if (!allIds.has(r.id)) fail(`نتيجة بحث بمعرّف غير معروف: ${r.id}`);
}

const rq = reviewQueue();
const independentlyFlagged = DHKAR.filter((d) => d.verification !== "verified-source");
if (rq.length !== independentlyFlagged.length)
  fail(`reviewQueue() يعيد ${rq.length} والتحقّق المستقل يقول ${independentlyFlagged.length}`);
for (const d of rq) {
  if (!d.verificationNote) fail(`«${d.id}» في طابور المراجعة بلا مبرر مكتوب`);
}
ok(`طابور المراجعة: ${rq.length} ذكرًا`);

const un = unconfirmedNumbers();
let unconfirmedTotal = 0;
for (const d of DHKAR)
  for (const s of d.sources) if (s.numberVerification !== "confirmed") unconfirmedTotal++;
if (un.length !== unconfirmedTotal)
  fail(`unconfirmedNumbers() يعيد ${un.length} مقابل ${unconfirmedTotal} بالحساب المستقل`);
ok(`مراجع بأرقام غير مُتحقَّق منها: ${un.length}`);

/* textFor يجب أن يفضّل صيغة المساء عند وجودها */
for (const d of DHKAR) {
  if (d.eveningText) {
    if (textFor(d, "evening") !== d.eveningText) fail(`«${d.id}»: textFor(evening) لا يعيد الصيغة المسائية`);
    if (textFor(d, "morning") !== d.text) fail(`«${d.id}»: textFor(morning) لا يعيد الصيغة الصباحية`);
  } else if (textFor(d, "evening") !== d.text) {
    fail(`«${d.id}»: textFor(evening) يخالف النص الأساسي`);
  }
}

/* normalize يجب أن يوحّد الهمزات والتشكيل: النص المُشكَّل والمسطَّل ي نهائيًا واحد */
const normSamples = [
  ["اللَّهُمَّ صَلِّ", "اللهم صل"],
  ["أَسْتَغْفِرُ اللَّهَ", "استغفر الله"],
  ["إِيَّاكَ نَعْبُدُ", "اياك نعبد"],
  ["بِسْمِ اللَّهِ الرَّحْمَنِ", "بسم الله الرحمن"],
  ["الصَّبْرُ", "الصبر"],
];
for (const [input, plain] of normSamples) {
  const got = normalize(input);
  if (got !== normalize(plain))
    fail(`normalize(${JSON.stringify(input)}) = ${JSON.stringify(got)} والمتوقع ${JSON.stringify(normalize(plain))}`);
}
/* البحث يجب أن ينجح بالنص المُشكَّل وبلا تشكيل معًا */
if (searchAdhkar("استغفر").length === 0 && searchAdhkar("أَسْتَغْفِرُ").length === 0)
  fail("البحث عن الاستغفار لم ينجح بالشكل المُشكَّل ولا المسطَّل");

/* ---------------------------------------------------------------- */
/* 5. فحص شبكي اختياري                                               */
/* ---------------------------------------------------------------- */

if (CHECK_NETWORK) {
  const urls = new Set();
  for (const d of DHKAR) {
    if (d.audio) urls.add(d.audio);
    for (const s of d.sources) if (s.url) urls.add(s.url);
  }
  const UA =
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36";
  let blocked = 0;
  const reachable = [];
  console.log(`\n— فحص ${urls.size} رابطًا عبر الشبكة —`);
  for (const url of urls) {
    try {
      const res = await fetch(url, {
        method: "GET",
        headers: { "User-Agent": UA, Accept: "text/html,application/xhtml+xml,*/*" },
        redirect: "follow",
      });
      if (res.status >= 400 && res.status !== 403 && res.status !== 429)
        fail(`رابط غير صالح (${res.status}): ${url}`);
      else if (res.status === 403 || res.status === 429) {
        // حماية ضد القوى الآلية: لا تعني أن الرابط منتهٍ، لكنها تعني أن
        // التحقق الآلي تعذّر — تُسجَّل صراحةً ولا تُحسب نجاحًا.
        blocked++;
        ok(`حُجب آليًا (${res.status}) — يحتاج تحققًا يدويًا عبر المتصفح: ${url}`);
      } else reachable.push(`${res.status} ${url}`);
    } catch (err) {
      fail(`تعذّر الوصول: ${url} — ${err.message}`);
    }
  }
  if (reachable.length) ok(`${reachable.length} رابطًا استجاب بنجاح من أصل ${urls.size}`);
  if (blocked > 0)
    notes.push(
      `${blocked} رابطًا حجبتها حماية القوى الآلية على sunnah.com — فُتحت يدويًا عبر المتصفح أثناء التوثيق`
    );
}

/* ---------------------------------------------------------------- */
/* 6. التقرير                                                        */
/* ---------------------------------------------------------------- */

const width = 62;
console.log("\n" + "─".repeat(width));
console.log("  فحص بيانات الأذكار — src/data/adhkar.ts");
console.log("─".repeat(width));
for (const n of notes)
  console.log(n.startsWith("حُجب") || n.startsWith("يحتاج") ? "  ! " + n : "  ✓ " + n);
if (problems.length === 0) {
  console.log("─".repeat(width));
  console.log(`  نجح الفحص: 0 مخالفة في ${DHKAR.length} ذكرًا.`);
  console.log("─".repeat(width) + "\n");
  process.exit(0);
} else {
  console.log("─".repeat(width));
  for (const p of problems) console.log("  ✗ " + p);
  console.log("─".repeat(width));
  console.log(`  فشل الفحص: ${problems.length} مخالفة.`);
  console.log("─".repeat(width) + "\n");
  process.exit(1);
}
